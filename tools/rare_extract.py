"""Extract rare and rare-elite NPCs and their spawn points from the CMaNGOS
Classic database dump and write kUI's RareData.lua.

    python3 rare_extract.py <ClassicDB_*.sql.gz> <out RareData.lua>
"""
import sys
from collections import defaultdict
import cmangos_extract as cx

cx.WANT = {
    "creature_template": ["Entry", "Name", "SubName", "MinLevel", "MaxLevel", "Rank"],
    "creature": ["guid", "id", "map", "position_x", "position_y"],
    "creature_spawn_entry": ["guid", "entry"],
    "gameobject_template": ["entry", "type", "name"],
    "gameobject": ["guid", "id", "map", "position_x", "position_y"],
    "gameobject_spawn_entry": ["guid", "entry"],
}
import re
CHEST = re.compile(r"(Chest|Footlocker|Strongbox|Coffer|Lockbox|Buried Treasure)$")
NOT_CHEST = re.compile(r"^(Alliance|Horde|Darkmoon)")
FINDS = {"Giant Clam", "Un'Goro Dirt Pile", "Green Power Crystal", "Yellow Power Crystal", "Blue Power Crystal",
         "Red Power Crystal", "Bloodpetal Sprout", "Half-Buried Bottle"}
MAX_OBJ_POINTS = 60
MAX_POINTS = 16

def lua_str(s):
    return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'

def main(src, out):
    rows = cx.load(src)
    rares = {}
    for e, name, sub, lo, hi, rank in rows["creature_template"]:
        if rank in ("2", "4") and name:
            rares[int(e)] = dict(name=name, sub=sub if sub not in (None, "NULL") else "", lo=int(lo), hi=int(hi), elite=rank == "4")
    guid_pos = {}
    pts = defaultdict(list)
    for guid, cid, mp, x, y in rows["creature"]:
        if mp not in ("0", "1"):
            continue
        guid_pos[guid] = (int(mp), float(x), float(y))
        if int(cid) in rares:
            pts[int(cid)].append(guid_pos[guid])
    for guid, entry in rows.get("creature_spawn_entry", []):
        if int(entry) in rares and guid in guid_pos:
            pts[int(entry)].append(guid_pos[guid])
    n = 0
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- kUI · rare NPCs, generated by rare_extract.py from the CMaNGOS Classic\n")
        f.write("-- database (GPL-2.0, github.com/cmangos/classic-db). Do not edit by hand.\n")
        f.write("-- r[npcID] = { name, minLevel, maxLevel, elite, continent (0 EK, 1 Kalimdor), \"x,y;x,y\" world spawn points }\n")
        f.write("local _, ns = ...\nlocal r = {}\nns.RareData = r\n")
        for cid in sorted(pts):
            ps = pts[cid]
            mp = ps[0][0]
            seen, coords = set(), []
            for m, x, y in ps:
                key = (round(x), round(y))
                if m == mp and key not in seen:
                    seen.add(key)
                    coords.append("%.0f,%.0f" % (x, y))
            r = rares[cid]
            f.write("r[%d]={%s,%d,%d,%s,%d,\"%s\"}\n" % (cid, lua_str(r["name"]), r["lo"], r["hi"], "true" if r["elite"] else "false", mp, ";".join(coords[:MAX_POINTS])))
            n += 1
        # Treasure chests and other things lying around to loot
        objs = {}
        for e, typ, name in rows["gameobject_template"]:
            if typ != "3" or not name:
                continue
            if name in FINDS:
                objs[int(e)] = (name, "find")
            elif CHEST.search(name) and not NOT_CHEST.search(name):
                objs[int(e)] = (name, "chest")
        gpos, opts = {}, defaultdict(list)
        for guid, oid, mp, x, y in rows["gameobject"]:
            if mp in ("0", "1"):
                gpos[guid] = (int(mp), float(x), float(y))
                if int(oid) in objs:
                    opts[int(oid)].append(gpos[guid])
        for guid, entry in rows.get("gameobject_spawn_entry", []):
            if int(entry) in objs and guid in gpos:
                opts[int(entry)].append(gpos[guid])
        f.write("-- t[objectID] = { name, \"chest\" or \"find\", { [continent] = \"x,y;x,y\" } }\n")
        f.write("local t = {}\nns.TreasureData = t\n")
        nt, npts = 0, 0
        for oid in sorted(opts):
            name, kind = objs[oid]
            per = defaultdict(list)
            seen = set()
            for m, x, y in opts[oid]:
                key = (m, round(x / 5), round(y / 5))
                if key not in seen:
                    seen.add(key)
                    per[m].append("%.0f,%.0f" % (x, y))
            parts = ",".join("[%d]=\"%s\"" % (m, ";".join(v)) for m, v in sorted(per.items()))
            f.write("t[%d]={%s,\"%s\",{%s}}\n" % (oid, lua_str(name), kind, parts))
            nt += 1
            npts += sum(len(v) for v in per.values())
    print("rares with spawns:", n, "of", len(rares))
    print("treasure objects:", nt, "spawn points:", npts)

if __name__ == "__main__":
    main(*sys.argv[1:3])
